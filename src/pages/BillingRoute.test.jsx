import { describe, it, expect, vi, afterEach } from 'vitest';
import { render, screen, fireEvent, cleanup, waitFor, within } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import Settings from './Settings';
import Pricing from './Pricing';
globalThis.IntersectionObserver = class { observe() {} unobserve() {} disconnect() {} };
const checkout = vi.hoisted(() => vi.fn());
const fixture = vi.hoisted(() => ({ user: {id:'owner-a',email:'fixture@example.invalid'}, refetch: vi.fn() }));
vi.mock('@/lib/flags', () => ({ isNewShell: () => true }));
vi.mock('@/lib/creem', async importOriginal => ({ ...(await importOriginal()), openCheckout:checkout }));
vi.mock('@/lib/AuthContext', () => ({ useAuth: () => ({ user:fixture.user, isLoadingAuth:false, isLoadingPublicSettings:false }), AuthProvider:({children})=>children, FallbackAuthProvider:({children})=>children }));
vi.mock('@/hooks/useCurrentUser', () => ({ useCurrentUser: () => ({ user:fixture.user }) }));
vi.mock('@/hooks/useSubscription', () => ({ default:()=>({plan:'free',refetch:fixture.refetch}) }));
vi.mock('@/components/i18n/i18nProvider', () => ({ useI18n: () => ({ t:key=>key, language:'english', isRTL:false, languages:{} }), I18nProvider:({children})=>children }));
vi.mock('@/components/privacy/PrivacyGate', () => ({ default:({children})=>children }));
vi.mock('@/shell/AppShell', () => ({ default:({children})=><div>{children}</div> }));
vi.mock('@/lib/analytics', () => ({trackPageView:vi.fn(),identifyUser:vi.fn()}));
vi.mock('@/lib/errorTracking', () => ({initErrorTracking:vi.fn(),captureError:vi.fn()}));
vi.mock('@/lib/NavigationTracker', () => ({default:()=>null}));
vi.mock('@/utils/storageCleanup', () => ({cleanupStorage:vi.fn()}));
vi.mock('@/components/ClerkLocaleProvider', () => ({default:({children})=>children}));
vi.mock('@/pages.config', () => ({pagesConfig:{mainPage:'Home',Layout:({children})=>children,Pages:{Settings,Pricing,LandingPage:()=>null,Blog:()=>null,BlogPost:()=>null,PrivacyPolicy:()=>null,TermsOfService:()=>null,Accessibility:()=>null,Contact:()=>null}}}));
afterEach(()=>{cleanup();checkout.mockClear();vi.unstubAllEnvs()});
describe('authenticated billing route', () => {
 it('shows the selected plan with purchases unavailable by default', async () => {
  vi.stubEnv('VITE_SUBSCRIPTION_CHECKOUT_ENABLED', undefined);
  vi.stubEnv('VITE_NEW_SHELL','true');
  const { NewShellRoutes } = await import('../App.jsx');
  render(<MemoryRouter initialEntries={['/pricing?plan=lite']}><NewShellRoutes/></MemoryRouter>);
  fireEvent.click(await screen.findByRole('link',{name:'spxLibrary.accountSettings'}));
  expect(await screen.findByText('Lite')).toBeInTheDocument();
  expect(screen.getByText('settings.billing.checkoutUnavailable')).toBeInTheDocument();
  expect(screen.queryByRole('button', { name: 'settings.billing.upgradeNow' })).not.toBeInTheDocument();
  expect(checkout).not.toHaveBeenCalled();
 });

 it('opens selected Lite in real billing UI, without calling checkout', async () => {
  vi.stubEnv('VITE_SUBSCRIPTION_CHECKOUT_ENABLED', 'true');
  vi.stubEnv('VITE_NEW_SHELL','true');
  const { NewShellRoutes } = await import('../App.jsx');
  render(<MemoryRouter initialEntries={['/pricing?plan=lite']}><NewShellRoutes/></MemoryRouter>);
  fireEvent.click(await screen.findByRole('link',{name:'spxLibrary.accountSettings'}));
  expect(await screen.findByRole('tab',{name:'settings.tabs.billing'})).toHaveAttribute('data-state','active');
  expect(await screen.findByText('Lite')).toBeInTheDocument();
  expect(screen.getByRole('status')).toHaveTextContent('spxLibrary.planReview');
  expect(checkout).not.toHaveBeenCalled();
  const card = /** @type {HTMLElement} */ (screen.getByText('Lite').closest('.clay-card'));
  fireEvent.click(within(card).getByRole('button', {name:'settings.billing.upgradeNow'}));
  expect(screen.getByRole('alertdialog')).toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', {name:'Cancel'}));
  expect(checkout).not.toHaveBeenCalled();
  await waitFor(()=>expect(checkout).not.toHaveBeenCalled());
 });
});
